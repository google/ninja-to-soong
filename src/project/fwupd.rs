// meson builds the Rust crates in rust/ with a cargo wrapper script, which cannot
// run in Soong. They are replaced by Soong Rust modules using the crates
// available in Android.
const RUST_DIR: &str = "rust";
const RUST_FFI_TARGET: &str = "rust/libfwupd_ffi.a";
const RUST_FFI_MODULE: &str = "libfwupd_ffi";
const RUST_LIB_MODULE: &str = "libfwupd";
const RUST_EDITION: &str = "2021";

// The daemon and the client link the frozen AIDL interface instead of the AIDL
// sources generated by meson, so that Soong checks them against the frozen API.
const AIDL_NDK_MODULE: &str = "org.freedesktop.fwupd-V1-ndk";

// The init script and the VINTF fragment are shared with
