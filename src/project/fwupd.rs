const CLIENT_TARGET: &str = "src/fwupdmgr";
const TOOL_TARGET: &str = "src/fwupdtool";
const QUIRKS_TARGET: &str = "builtin.quirk.gz";
const LIBFWUPD_TARGET: &str = "libfwupd/libfwupd.a";
const LIBFWUPD_MODULE: &str = "fwupd_libfwupd_libfwupd_a";
const LIBFWUPD_HEADERS_MODULE: &str = "fwupd_libfwupd_headers";
